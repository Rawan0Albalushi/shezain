export function translate(locale, key) {
    return dictionary[locale]?.[key] ?? dictionary.ar[key] ?? key;
}

export function localized(locale, item, field) {
    if (!item) {
        return '';
    }

    return item[`${field}_${locale}`] || item[`${field}_ar`] || '';
}

export function variantSummary(locale, item) {
    return [localized(locale, item, 'color'), item?.size].filter(Boolean).join(' · ');
}
